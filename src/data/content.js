export function initials(name) {
  return name
    .split(/\s+/)
    .filter((w) => !/^(Leader|Ing\.|Engr\.|Dr\.)$/i.test(w))
    .slice(0, 2)
    .map((w) => w[0])
    .join('')
    .toUpperCase();
}
